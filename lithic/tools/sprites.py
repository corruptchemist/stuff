"""
Hand-authored 16x16 item/block sprites in the vanilla Minecraft idiom.

Each sprite is a 16-row x 16-col character grid. Characters index into PALETTE.
'.' is transparent. Authoring as text grids (rather than procedural noise) is
what lets these read as deliberate pixel art instead of coloured static.

Style rules being followed:
  - 3-4 shades per material: shadow / base / light / highlight
  - light source upper-left, so highlights sit top-left and shadow bottom-right
  - tools drawn on the diagonal, handle running bottom-left to top-right
  - silhouettes kept chunky; detail that does not read at 16px is noise

Run:  python3 tools/sprites.py           -> writes assets + contact sheet
"""

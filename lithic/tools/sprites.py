def _validate(name, grid):
    rows = [r for r in grid.strip("\n").split("\n")]
    if len(rows) != 16:
        raise ValueError(f"{name}: {len(rows)} rows, expected 16")
    for y, row in enumerate(rows):
        if len(row) != 16:
            raise ValueError(f"{name}: row {y} is {len(row)} wide, expected 16")
        for ch in row:
            if ch not in PALETTE:
                raise ValueError(f"{name}: row {y} uses undefined char {ch!r}")
    return rows


def _shade(rgb, factor):
    return tuple(max(0, min(255, int(v * factor))) for v in rgb)


def to_pixels(grid_rows, bevel=True):
    """Grid -> 16x16 RGBA. Optionally darkens the bottom edge of the silhouette."""
    px = [[(0, 0, 0, 0)] * 16 for _ in range(16)]
    for y, row in enumerate(grid_rows):
        for x, ch in enumerate(row):
            rgb = PALETTE[ch]
            if rgb is not None:
                px[y][x] = (rgb[0], rgb[1], rgb[2], 255)
    if bevel:
        # one-pixel darker lip along the bottom of each column, the cheap trick
        # vanilla uses to stop items looking flat
        for x in range(16):
            for y in range(15, -1, -1):
                if px[y][x][3]:
                    c = _shade(px[y][x][:3], 0.7)
                    px[y][x] = (c[0], c[1], c[2], 255)
                    break
    return px


def write_png(path, px, scale=1):
    w = h = 16 * scale
    raw = b""
    for y in range(h):
        raw += b"\x00"
        for x in range(w):
            raw += bytes(px[y // scale][x // scale])

    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    blob = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(blob)


def contact_sheet(entries, path, scale=6, cols=5, pad=4):
    """One big magnified grid of every sprite, for eyeballing the whole set."""
    cell = 16 * scale + pad * 2
    rows = (len(entries) + cols - 1) // cols
    W, H = cols * cell, rows * cell
    canvas = [[(58, 58, 64, 255)] * W for _ in range(H)]
    for idx, (_name, px) in enumerate(entries):
        cx, cy = (idx % cols) * cell + pad, (idx // cols) * cell + pad
        for y in range(16 * scale):
            for x in range(16 * scale):
                p = px[y // scale][x // scale]
                if p[3]:
                    canvas[cy + y][cx + x] = p
                else:
                    # checkerboard so transparent areas are obvious
                    tone = 40 if ((x // scale + y // scale) // 2) % 2 == 0 else 48
                    canvas[cy + y][cx + x] = (tone, tone, tone, 255)

    raw = b""
    for y in range(H):
        raw += b"\x00" + b"".join(bytes(canvas[y][x]) for x in range(W))

    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", W, H, 8, 6, 0, 0, 0)
    blob = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(blob)


def main():
    sheet = []
    for name, grid in ITEMS.items():
        px = to_pixels(_validate(name, grid), bevel=True)
        write_png(os.path.join(OUT, "item", f"{name}.png"), px)
        sheet.append((name, px))
    for name, grid in BLOCKS.items():
        # blocks tile, so no bevel - it would show as a seam
        px = to_pixels(_validate(name, grid), bevel=False)
        write_png(os.path.join(OUT, "block", f"{name}.png"), px)
        sheet.append((name, px))

    contact_sheet(sheet, SHEET)
    print(f"{len(ITEMS)} item + {len(BLOCKS)} block sprites written")
    print("order: " + ", ".join(n for n, _ in sheet))
    print(f"contact sheet: {os.path.normpath(SHEET)}")


if __name__ == "__main__":
    main()
